// Generate TypeScript types from directus/snapshot.yaml → types/directus-schema.ts.
// Run after every schema change: npm run typegen (npm run schema:snapshot does it too).
// The output follows the @directus/sdk convention: Schema maps collection → Item[].

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { parse } from 'yaml';

const root = resolve(import.meta.dirname, '../..');
const snapshot = parse(readFileSync(resolve(root, 'directus/snapshot.yaml'), 'utf8'));
const out = resolve(root, 'types/directus-schema.ts');

type Field = { collection: string; field: string; type: string; meta: any; schema: any };
type Relation = { collection: string; field: string; related_collection: string | null; meta: any };

const collections: string[] = snapshot.collections.filter((c: any) => c.schema).map((c: any) => c.collection);
const fields: Field[] = snapshot.fields;
const relations: Relation[] = snapshot.relations;

const typeName = (c: string) =>
	c.replace(/(^|_)([a-z0-9])/g, (_, __, ch: string) => ch.toUpperCase()).replace(/s$/, '').replace(/ie$/, 'y') || c;
const names = new Map(collections.map((c) => [c, typeName(c)]));
// disambiguate if singularising collided
const seen = new Map<string, number>();
for (const [c, n] of names) {
	const k = seen.get(n) ?? 0;
	if (k) names.set(c, n + (k + 1));
	seen.set(n, k + 1);
}

const pkType = (c: string) => {
	const pk = fields.find((f) => f.collection === c && f.schema?.is_primary_key);
	return pk && ['integer', 'bigInteger'].includes(pk.type) ? 'number' : 'string';
};
const relatedRef = (c: string | null) => (c && names.has(c) ? `${pkType(c)} | ${names.get(c)}` : 'string');

function tsType(f: Field): string | null {
	const special: string[] = f.meta?.special ?? [];
	if (f.type === 'alias') {
		if (special.includes('group') || special.includes('no-data')) return null;
		const rel = relations.find((r) => r.related_collection === f.collection && r.meta?.one_field === f.field);
		return rel ? `(${relatedRef(rel.collection)})[]` : 'unknown[]';
	}
	const m2o = relations.find((r) => r.collection === f.collection && r.field === f.field && r.related_collection);
	let t: string;
	if (m2o) t = relatedRef(m2o.related_collection);
	else if (f.meta?.interface === 'tags') t = 'string[]';
	else if (f.meta?.options?.choices?.length) t = f.meta.options.choices.map((c: any) => JSON.stringify(c.value)).join(' | ');
	else
		t = ({ integer: 'number', bigInteger: 'number', float: 'number', decimal: 'number', boolean: 'boolean', json: 'unknown' } as Record<string, string>)[f.type] ?? 'string';
	return f.schema?.is_nullable === false || f.schema?.is_primary_key ? t : `${t} | null`;
}

let ts = `// Generated by scripts/typegen/typegen.ts from directus/snapshot.yaml. Do not edit.\n// Run \`npm run typegen\` after every schema change.\n\n`;
for (const c of collections) {
	ts += `export interface ${names.get(c)} {\n`;
	for (const f of fields.filter((x) => x.collection === c)) {
		const t = tsType(f);
		if (t) ts += `\t${f.field}: ${t};\n`;
	}
	ts += `}\n\n`;
}
ts += `export interface Schema {\n${collections.map((c) => `\t${c}: ${names.get(c)}[];`).join('\n')}\n}\n`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, ts);
console.log(`typegen: ${collections.length} collections → ${out.replace(root + '/', '')}`);
